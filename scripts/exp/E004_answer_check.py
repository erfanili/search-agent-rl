#!/usr/bin/env python
"""E004 answer-span check (Erfan, 2026-11-21): parsed-answer length and unclosed share, step 20 against steps 1-3.

  .venv-verl/bin/python scripts/exp/E004_answer_check.py --run E004-A-s0 [--watch --kill]

Measure: parsed answer span = first <answer> span of the model text with environment text stripped (unclosed ->
  text to the end), i.e. the span the alias_match reward reads (agent/reward.py:answer_span_info in the worktree).
  Words = whitespace split. Unclosed = no </answer> after the first <answer>; share over rollouts with an <answer>.
Steps 1-3 reference: all 960 episodes of the pilot E004-A-pilot (arm A recipe, seed 0, exactly steps 1-3, agent
  loop dumps; labels joined by question from mix50). Cross-check: E004-A-s0's own part-1 dumps (rollouts.part1/, its
  first 1,600 episodes, about steps 1-5).
Step 20: arm A had passed step 20 before the logging existed, so it was resumed from ckpt/global_step_20 with the
  logging on. The checked step is the first logged step (21): rollouts generated by the step-20 checkpoint.
Stop rule, applied to all rollouts and to each label: mean words > 2 x the steps 1-3 mean, or unclosed share > 0.05.
--watch: wait until that step is in reward_steps.jsonl. --kill: on a stop, kill arm A's training and write STOP.
Output: $DATA_ROOT/logs/E004/<run>/answer_check.json (+ STOP on a stop).
"""
import argparse, glob, json, os, re, subprocess, sys, time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
from agent.paths import DATA  # noqa: E402
from agent.qa_metrics import strip_environment_text  # noqa: E402

SPECIAL = re.compile(r"<\|(im_end|endoftext|im_start)\|>")
QRE = re.compile(r"Question: ([^\n]*)\n<\|im_end\|>")


def span_info(text):  # = sar-alias-reward agent/reward.py:answer_span_info (main's agent/ does not have it yet)
    text = strip_environment_text(text)
    i = text.find("<answer>")
    if i < 0:
        return None, None
    rest = text[i + len("<answer>"):]
    j = rest.find("</answer>")
    return len((rest[:j] if j >= 0 else rest).strip().split()), j < 0


def p95(v):
    v = sorted(v)
    h = (len(v) - 1) * 0.95
    lo = int(h)
    return v[lo] + (h - lo) * (v[min(lo + 1, len(v) - 1)] - v[lo])


def cell(items):
    w = [x for x, _ in items if x is not None]
    u = [float(y) for x, y in items if x is not None]
    return {"n_answer": len(w), "n_no_answer": len(items) - len(w), "mean_words": sum(w) / len(w), "p95_words": p95(w),
            "share_unclosed": sum(u) / len(u)}


def dump_stats(dump_dir, labels):
    by = {"all": [], "knowable": [], "unknowable": []}
    for p in glob.glob(os.path.join(dump_dir, "*.jsonl")):
        for line in open(p):
            e = json.loads(line)
            info = span_info(SPECIAL.sub("", "".join(s["text"] for s in e["segments"])))
            by["all"].append(info)
            by[labels[QRE.findall(e["prompt_text"])[-1].strip()]].append(info)
    return {k: cell(v) for k, v in by.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="E004-A-s0")
    ap.add_argument("--step", type=int, default=21)
    ap.add_argument("--watch", action="store_true")
    ap.add_argument("--kill", action="store_true")
    a = ap.parse_args()
    E = os.path.join(DATA, "logs", "E004")
    out = os.path.join(E, a.run)
    labels = {r["question"].strip(): r["label"] for r in map(json.loads, open(os.path.join(DATA, "verl_data", "e004", "mix50",
                                                                                            "e004_train_mix50.jsonl")))}
    ref = dump_stats(os.path.join(E, "E004-A-pilot", "rollouts"), labels)
    cross = dump_stats(os.path.join(out, "rollouts.part1"), labels)
    rec = None
    while rec is None:
        for line in open(os.path.join(out, "reward_steps.jsonl")):
            r = json.loads(line)
            if r["split"] == "train" and r["step"] == a.step and "answer" in r:
                rec = r
        if rec is None:
            if not a.watch:
                sys.exit(f"step {a.step} with answer stats not in reward_steps.jsonl yet")
            time.sleep(60)
    cur = {"all": rec["answer"]["all"], **rec["answer"]["by_label"]["e004_label"]}
    flags = []
    for k in ("all", "knowable", "unknowable"):
        if cur[k]["mean_words"] is not None and cur[k]["mean_words"] > 2 * ref[k]["mean_words"]:
            flags.append(f"{k}: mean words {cur[k]['mean_words']:.2f} > 2 x {ref[k]['mean_words']:.2f}")
        if cur[k]["share_unclosed"] is not None and cur[k]["share_unclosed"] > 0.05:
            flags.append(f"{k}: unclosed share {cur[k]['share_unclosed']:.3f} > 0.05")
    res = {"checked_step": a.step, "checked": cur, "ref_steps1_3_pilot": ref, "crosscheck_A_s0_dumps": cross,
           "stop": bool(flags), "flags": flags, "time": time.strftime("%F %T")}
    json.dump(res, open(os.path.join(out, "answer_check.json"), "w"), indent=2)
    print(json.dumps(res, indent=2), flush=True)
    if flags and a.kill:
        open(os.path.join(out, "STOP"), "w").write("\n".join(flags) + "\n")
        subprocess.run(["pkill", "-u", str(os.getuid()), "-f", f"default_local_dir={out}/ckpt"])
        print("STOP: arm A training killed", flush=True)


if __name__ == "__main__":
    main()
